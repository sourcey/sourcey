/** Starlight's sidebar as native navigation, with its translated labels. */
import type { GroupConfig, NavigationItem } from "../../config.js";
import type { JsonValue } from "../../core/markdown-components.js";
import { toJson, type Value } from "../javascript.js";
import { groupId, placeUnlisted, topLevelGroups } from "../navigation.js";
import { lineAt } from "../text-edits.js";
import { STARLIGHT_OPENAPI, withoutPrefix, type Locale, type SourceEntry, type StarlightContext } from "./starlight-model.js";
import { isAbsoluteHttpUrl } from "../../site-url.js";

export interface NavigationResult {
  groups: GroupConfig[];
  /** Translated labels by locale, keyed by navigation ID. */
  messages: Map<string, Record<string, string>>;
}

export async function convertSidebar(
  context: StarlightContext,
  sidebar: Value | undefined,
  entries: SourceEntry[],
  locales: Locale[],
  mount: string,
  hostBase: string,
): Promise<NavigationResult> {
  const { root, diagnostics } = context;
  const messages = new Map<string, Record<string, string>>();
  const listed = new Set<string>();
  const defaults = entries.filter((entry) => !entry.locale);
  const bySlug = new Map(defaults.map((entry) => [entry.slug, entry]));
  const fail = (message: string, value?: Value) =>
    diagnostics.error({ file: root.configFile, line: lineAt(root.scope.source, value?.node.start), code: "starlight-sidebar", message });
  const langToLocale = new Map(locales.map((locale) => [locale.lang, locale.key]));
  const translate = (id: string, translations: JsonValue | undefined) => {
    if (!translations || typeof translations !== "object" || Array.isArray(translations)) return;
    for (const [lang, label] of Object.entries(translations)) {
      const locale = langToLocale.get(lang);
      if (!locale || typeof label !== "string") continue;
      messages.set(locale, { ...messages.get(locale), [id]: label });
    }
  };
  const page = (entry: SourceEntry, label?: string, translations?: JsonValue): NavigationItem => {
    listed.add(entry.documentPath);
    if (translations) translate(entry.documentPath, translations);
    return label ? { page: entry.documentPath, label } : entry.documentPath;
  };
  const collator = new Intl.Collator(locales[0].lang);
  const order = (entry: SourceEntry) => {
    const sidebarData = entry.frontmatter.sidebar as { order?: number } | undefined;
    return typeof sidebarData?.order === "number" ? sidebarData.order : Number.MAX_VALUE;
  };
  const hidden = (entry: SourceEntry) => (entry.frontmatter.sidebar as { hidden?: boolean } | undefined)?.hidden === true;

  /** Starlight's autogenerated group: directories become nested groups, ordered by `sidebar.order` then slug. */
  const autogenerate = (directory: string, id: string, collapsed: boolean | undefined): NavigationItem[] => {
    const prefix = withoutPrefix(directory, mount) ?? directory;
    interface Dir { slug: string; children: Map<string, Dir | SourceEntry> }
    const tree: Dir = { slug: prefix, children: new Map() };
    const inside = defaults
      .filter((entry) => !hidden(entry) && (entry.documentPath === prefix || entry.documentPath.startsWith(`${prefix}/`)))
      .sort((a, b) => b.documentPath.split("/").length - a.documentPath.split("/").length);
    for (const entry of inside) {
      const parts = entry.documentPath === prefix ? [] : entry.documentPath.slice(prefix.length + 1).split("/");
      let node = tree;
      for (const [index, part] of parts.entries()) {
        const leaf = index === parts.length - 1;
        const existing = node.children.get(part);
        if (leaf) {
          if (existing && "children" in existing) existing.children.set("index", entry);
          else node.children.set(part, entry);
        } else {
          if (!existing || !("children" in existing)) node.children.set(part, { slug: `${node.slug}/${part}`, children: new Map() });
          node = node.children.get(part) as Dir;
        }
      }
      if (!parts.length) tree.children.set("index", entry);
    }
    const weight = (item: Dir | SourceEntry): number =>
      "children" in item ? Math.min(...[...item.children.values()].map(weight)) : order(item);
    const items = (dir: Dir, parentId: string): NavigationItem[] =>
      [...dir.children.entries()]
        .sort(([, a], [, b]) => {
          const [left, right] = [weight(a), weight(b)];
          if (left !== right) return left < right ? -1 : 1;
          return collator.compare(a.slug, b.slug);
        })
        .map(([key, item]) =>
          "children" in item
            ? { group: key, id: [parentId, key].filter(Boolean).join("/"), ...(collapsed ? { collapsed } : {}), pages: items(item, [parentId, key].filter(Boolean).join("/")) }
            : page(item),
        );
    return items(tree, id);
  };

  const item = async (value: Value, parentId: string, index: number): Promise<NavigationItem | undefined> => {
    if (value.kind === "spread") {
      if (value.value.kind === "reference" && value.value.binding.module === STARLIGHT_OPENAPI) return undefined;
      fail("A spread in the Starlight sidebar is not static", value);
      return undefined;
    }
    const data = toJson(value);
    if (!data.ok) {
      fail(`A Starlight sidebar entry is not static: ${data.reason}`, value);
      return undefined;
    }
    const raw = typeof data.value === "string" ? { slug: data.value } : (data.value as Record<string, JsonValue>);
    const label = typeof raw.label === "string" ? raw.label : undefined;
    if (raw.badge !== undefined || raw.attrs !== undefined)
      diagnostics.review({ file: root.configFile, line: lineAt(root.scope.source, value.node.start), code: "starlight-sidebar", message: `Sidebar badge and attrs on "${label ?? raw.slug ?? raw.link}" have no native equivalent` });
    if (typeof raw.slug === "string") {
      const slug = raw.slug === "index" ? "" : (withoutPrefix(raw.slug, mount) ?? raw.slug);
      const entry = bySlug.get(slug);
      if (!entry) {
        fail(`Sidebar slug "${raw.slug}" matches no document`, value);
        return undefined;
      }
      return page(entry, label, raw.translations);
    }
    if (typeof raw.link === "string") {
      if (isAbsoluteHttpUrl(raw.link)) return { href: raw.link, label: label ?? raw.link };
      const path = raw.link.replace(/^\/+|\/+$/g, "");
      const inMount = withoutPrefix(path, mount);
      const entry = inMount === undefined ? undefined : bySlug.get(inMount);
      if (entry) return page(entry, label, raw.translations);
      // A host page outside the documentation, published under the Astro base.
      return { href: `${hostBase}/${path}${path ? "/" : ""}`, label: label ?? raw.link };
    }
    const id = groupId(parentId, label ?? "", String(index));
    translate(id, raw.translations);
    const collapsed = raw.collapsed === true ? true : undefined;
    if (raw.autogenerate && typeof raw.autogenerate === "object" && !Array.isArray(raw.autogenerate)) {
      const directory = String(raw.autogenerate.directory ?? "");
      return { group: label ?? "", id, ...(collapsed ? { collapsed } : {}), pages: autogenerate(directory, id, (raw.autogenerate.collapsed as boolean | undefined) ?? collapsed) };
    }
    if (Array.isArray(raw.items) && value.kind === "object") {
      const pages: NavigationItem[] = [];
      const children = value.entries.get("items");
      for (const [childIndex, child] of (children?.kind === "array" ? children.items : []).entries()) {
        const converted = await item(child, id, childIndex);
        if (!converted) continue;
        // Starlight lets an `items` entry be an unlabelled autogenerate group; its pages join this group.
        if (typeof converted === "object" && "group" in converted && converted.group === "" && child.kind === "object" && child.entries.has("autogenerate"))
          pages.push(...converted.pages);
        else pages.push(converted);
      }
      return { group: label ?? "", id, ...(collapsed ? { collapsed } : {}), pages };
    }
    fail("A Starlight sidebar entry needs slug, link, items or autogenerate", value);
    return undefined;
  };

  const items: NavigationItem[] = [];
  if (sidebar?.kind === "array") {
    for (const [index, value] of sidebar.items.entries()) {
      const converted = await item(value, "", index);
      if (converted) items.push(converted);
    }
  } else if (sidebar) {
    fail("The Starlight sidebar must be a static array", sidebar);
  } else {
    items.push(...autogenerate("", "", undefined));
  }
  const groups = topLevelGroups(items);
  placeUnlisted(groups, defaults.map((entry) => entry.documentPath).filter((path) => !listed.has(path)));
  return { groups, messages };
}

