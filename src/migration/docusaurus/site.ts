/**
 * A Docusaurus site as its build sees it. `docusaurus.config.*` and sidebar
 * files are programs (they read files, branch on the environment, call
 * `require.resolve`), so they are loaded the way Docusaurus loads them, with the
 * project's own dependencies, under the production environment its build uses.
 */
import { realpath } from "node:fs/promises";
import { isAbsolute, relative } from "node:path";
import { createJiti } from "jiti";
import { load as parseYaml } from "js-yaml";
import type { Diagnostics } from "../diagnostics.js";
import type { ProjectFiles } from "../project-files.js";
import { DEFAULT_ADMONITIONS } from "./markdown.js";

const CONFIG_NAMES = ["docusaurus.config.ts", "docusaurus.config.mts", "docusaurus.config.cts", "docusaurus.config.js", "docusaurus.config.mjs", "docusaurus.config.cjs"];

/** `@docusaurus/plugin-content-docs` defaults that decide routes and navigation. */
const DOCS_DEFAULTS = {
  path: "docs",
  routeBasePath: "docs",
  include: ["**/*.{md,mdx}"],
  exclude: ["**/_*.{js,jsx,ts,tsx,md,mdx}", "**/_*/**", "**/*.test.{js,jsx,ts,tsx}", "**/__tests__/**"],
  sidebarCollapsed: true,
  sidebarCollapsible: true,
};

type Options = Record<string, unknown>;

/** One docs plugin instance, with the defaults applied. */
export interface DocsInstance {
  id: string;
  /** Project-relative content directory. */
  path: string;
  /** Route below the site's base URL, without slashes (`""` at the root). */
  routeBase: string;
  /** Project-relative sidebars file; `false` when sidebars are disabled, undefined for the autogenerated default. */
  sidebarPath: string | false | undefined;
  include: string[];
  exclude: string[];
  editUrl?: unknown;
  /** Whether its pages show when they last changed (`showLastUpdateTime`). */
  lastUpdated: boolean;
  numberPrefixes: boolean;
  sidebarCollapsed: boolean;
  sidebarCollapsible: boolean;
  /** Admonition keywords this instance's Markdown reads. */
  admonitions: string[];
  options: Options;
}

/** Another plugin or theme the site uses, by the name its configuration gives. */
export interface SitePlugin {
  name: string;
  options: Options;
}

/** `i18n.localeConfigs` entries: the label, direction, HTML language and translations directory. */
export interface LocaleOptions {
  label?: string;
  direction?: "ltr" | "rtl";
  htmlLang?: string;
  path?: string;
}

export interface DocusaurusSite {
  configFile: string;
  config: Options;
  /** The Docusaurus major version the project declares; 2.x reads content as MDX 1. */
  major: number;
  /** `/` or `/path/`. */
  baseUrl: string;
  url?: string;
  trailingSlash?: boolean;
  markdownFormat: "mdx" | "md" | "detect";
  /** The MDX 1 syntax Docusaurus 3 still reads before parsing (`markdown.mdx1Compat`), each on unless the site turns it off. */
  mdx1Compat: { headingIds: boolean; admonitions: boolean };
  /** The site's own `markdown.preprocessor`, called as Docusaurus calls it: with a document's absolute path and its text. */
  preprocessor?: (file: string, content: string) => string;
  staticDirectories: string[];
  docs: DocsInstance[];
  customCss: string[];
  plugins: SitePlugin[];
  /** The Google Analytics IDs the classic preset's `gtag` or the gtag plugin loads. */
  gtag: string[];
  /** The pages plugin's directory, unless the site disabled it. */
  pages?: string;
  /** The admonition keywords its Markdown pages read. */
  pageAdmonitions: string[];
  themeConfig: Options;
  locales: { defaultLocale: string; locales: string[]; path: string; configs: Record<string, LocaleOptions> };
  /** Loads a sidebars (or category metadata) file the way Docusaurus does. */
  load(path: string): Promise<unknown>;
}

export async function loadSite(project: ProjectFiles, diagnostics: Diagnostics): Promise<DocusaurusSite | undefined> {
  let configFile: string | undefined;
  for (const name of CONFIG_NAMES) if (!configFile && (await project.exists(name))) configFile = name;
  if (!configFile) {
    diagnostics.error({ file: "docusaurus.config.js", code: "docusaurus", message: "No Docusaurus configuration found in the project root" });
    return undefined;
  }
  const jiti = createJiti(project.absolute(configFile), { moduleCache: false });
  const load = async (path: string): Promise<unknown> => {
    if (/\.json$/.test(path)) return JSON.parse(await project.readText(path));
    if (/\.ya?ml$/.test(path)) return parseYaml(await project.readText(path));
    const module = (await production(() => jiti.import(project.absolute(path)))) as { default?: unknown };
    const value = module.default ?? module;
    return typeof value === "function" ? production(() => (value as () => unknown)()) : value;
  };
  let config: Options;
  try {
    config = (await load(configFile)) as Options;
  } catch (error) {
    diagnostics.error({
      file: configFile,
      code: "docusaurus",
      message: `Loading the Docusaurus configuration failed: ${(error as Error).message}`,
      suggestion: "Install the project's dependencies first; the migration loads the configuration as Docusaurus does.",
    });
    return undefined;
  }

  // Configuration code resolves paths (`require.resolve`) against the real directory.
  const realRoot = await realpath(project.root);
  const local = (path: string) => (isAbsolute(path) ? relative(path.startsWith(realRoot) ? realRoot : project.root, path).split("\\").join("/") : relativePath(path));
  const presets = entries(config.presets, local);
  const classic = presets.find((preset) => /(^|\/)(classic|preset-classic)$/.test(preset.name) || preset.name.includes("preset-classic"))?.options ?? {};
  const plugins = [...entries(config.plugins, local), ...entries(config.themes, local)];
  const instances = [
    ...(classic.docs === false ? [] : [{ ...((classic.docs as Options | undefined) ?? {}) }]),
    ...plugins.filter((plugin) => plugin.name.includes("plugin-content-docs")).map((plugin) => plugin.options),
  ];
  const markdown = (config.markdown ?? {}) as Options;
  const i18n = (config.i18n ?? {}) as Options;
  const pages = classic.pages === false ? undefined : String((classic.pages as Options | undefined)?.path ?? "src/pages");
  const manifest = (await project.exists("package.json")) ? (JSON.parse(await project.readText("package.json")) as Record<string, Record<string, string> | undefined>) : {};
  const range = manifest.dependencies?.["@docusaurus/core"] ?? manifest.devDependencies?.["@docusaurus/core"] ?? "";
  return {
    configFile,
    config,
    major: Number(range.match(/\d+/)?.[0] ?? 3),
    baseUrl: String(config.baseUrl ?? "/"),
    url: typeof config.url === "string" ? config.url : undefined,
    trailingSlash: typeof config.trailingSlash === "boolean" ? config.trailingSlash : undefined,
    markdownFormat: markdown.format === "md" || markdown.format === "detect" ? markdown.format : "mdx",
    mdx1Compat: {
      headingIds: (markdown.mdx1Compat as Options | undefined)?.headingIds !== false,
      admonitions: (markdown.mdx1Compat as Options | undefined)?.admonitions !== false,
    },
    ...(typeof markdown.preprocessor === "function"
      ? { preprocessor: (file: string, fileContent: string) => String((markdown.preprocessor as (input: { filePath: string; fileContent: string }) => unknown)({ filePath: project.absolute(file), fileContent })) }
      : {}),
    staticDirectories: ((config.staticDirectories as string[] | undefined) ?? ["static"]).map(relativePath),
    docs: instances.map((options) => docsInstance(options, local)),
    customCss: [((classic.theme as Options | undefined)?.customCss ?? [])].flat().map(String).map(local),
    plugins: plugins.filter((plugin) => !plugin.name.includes("plugin-content-docs")),
    gtag: [classic.gtag, ...plugins.filter((plugin) => plugin.name.includes("plugin-google-gtag")).map((plugin) => plugin.options)]
      .flatMap((options) => [(options as Options | undefined)?.trackingID ?? []].flat().map(String)),
    pages,
    pageAdmonitions: admonitionKeywords((classic.pages as Options | undefined)?.admonitions),
    themeConfig: (config.themeConfig ?? {}) as Options,
    locales: {
      defaultLocale: String(i18n.defaultLocale ?? "en"),
      locales: ((i18n.locales as string[] | undefined) ?? [String(i18n.defaultLocale ?? "en")]).map(String),
      path: relativePath(String(i18n.path ?? "i18n")),
      configs: (i18n.localeConfigs ?? {}) as Record<string, LocaleOptions>,
    },
    load,
  };
}

/** Configuration code branches on the environment its production build sets. */
async function production<T>(run: () => Promise<T> | T): Promise<T> {
  const previous = process.env.NODE_ENV;
  process.env.NODE_ENV = "production";
  try {
    return await run();
  } finally {
    if (previous === undefined) delete process.env.NODE_ENV;
    else process.env.NODE_ENV = previous;
  }
}

/** Plugin, preset and theme entries: a name, `[name, options]`, or a falsy value a condition left. */
function entries(list: unknown, local: (path: string) => string): SitePlugin[] {
  const name = (entry: string) => packageName(entry) ?? local(entry);
  return (Array.isArray(list) ? list : []).flatMap((entry): SitePlugin[] => {
    if (typeof entry === "string") return [{ name: name(entry), options: {} }];
    if (Array.isArray(entry) && typeof entry[0] === "string") return [{ name: name(entry[0]), options: (entry[1] ?? {}) as Options }];
    if (typeof entry === "function") return [{ name: (entry as { name?: string }).name || "an inline plugin", options: {} }];
    return [];
  });
}

/** The package a `require.resolve`d entry names, or a package name as written; undefined for the project's own file. */
function packageName(name: string): string | undefined {
  if (/^(?:\.{1,2}\/|\/)/.test(name) && !name.includes("/node_modules/")) return undefined;
  return name.match(/.*node_modules\/((?:@[^/]+\/)?[^/]+)/)?.[1] ?? name;
}

function relativePath(path: string): string {
  return path.replace(/^\.\//, "").replace(/\/+$/, "");
}

function docsInstance(options: Options, local: (path: string) => string): DocsInstance {
  const sidebarPath = options.sidebarPath;
  return {
    id: String(options.id ?? "default"),
    path: local(String(options.path ?? DOCS_DEFAULTS.path)),
    routeBase: String(options.routeBasePath ?? DOCS_DEFAULTS.routeBasePath).replace(/^\/+|\/+$/g, ""),
    sidebarPath: sidebarPath === false ? false : typeof sidebarPath === "string" ? local(sidebarPath) : undefined,
    include: (options.include as string[] | undefined) ?? DOCS_DEFAULTS.include,
    exclude: ((options.exclude as string[] | undefined) ?? DOCS_DEFAULTS.exclude).map((pattern) => pattern.replace(/^\.\//, "")),
    editUrl: options.editUrl,
    lastUpdated: options.showLastUpdateTime === true,
    numberPrefixes: options.numberPrefixParser !== false,
    sidebarCollapsed: options.sidebarCollapsed !== false,
    sidebarCollapsible: options.sidebarCollapsible !== false,
    admonitions: admonitionKeywords(options.admonitions),
    options,
  };
}

/** The admonition keywords a docs or pages plugin reads: Docusaurus's own, extended or replaced. */
function admonitionKeywords(admonitions: unknown): string[] {
  const keywords =
    admonitions && typeof admonitions === "object"
      ? [...((admonitions as Options).extendDefaults === false ? [] : DEFAULT_ADMONITIONS), ...(((admonitions as Options).keywords as string[] | undefined) ?? [])]
      : DEFAULT_ADMONITIONS;
  return [...new Set(keywords)];
}
