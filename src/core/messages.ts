/** Built-in chrome follows the declared language; authored messages take precedence. */
export function messagesFor(
  language: string,
  overrides: UiMessageOverrides = {},
): UiMessages & Pick<UiMessageOverrides, "navigation"> {
  return { ...english, ...translations[language.toLowerCase().split("-")[0]], ...overrides };
}
